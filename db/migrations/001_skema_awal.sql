-- 001_skema_awal.sql
-- Skema awal Monitoring KPSP PAUD (PostgreSQL / Supabase).
-- Semua tabel ada di schema `kpsp` (bukan `public`) agar TIDAK terekspos lewat
-- API REST/PostgREST bawaan Supabase. Aplikasi mengakses lewat role kpsp_app.
-- Sama persis dengan migrasi "kpsp_skema_awal" di project Supabase produksi.

CREATE SCHEMA IF NOT EXISTS kpsp;

-- Kelurahan wilayah kerja Puskesmas (tetap 6, lihat 003_seed_kelurahan.sql)
CREATE TABLE kpsp.kelurahan (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT UNIQUE NOT NULL);

-- PAUD / TK
CREATE TABLE kpsp.paud (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama         TEXT NOT NULL,
  kelurahan_id BIGINT NOT NULL REFERENCES kpsp.kelurahan(id),
  UNIQUE (nama, kelurahan_id));
CREATE INDEX ix_paud_kel ON kpsp.paud(kelurahan_id);

-- Pengguna: guru (terikat 1 PAUD) atau puskesmas (admin/petugas)
CREATE TABLE kpsp.pengguna (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,                 -- hash werkzeug (scrypt), bukan password asli
  nama          TEXT NOT NULL,
  hp            TEXT,
  peran         TEXT NOT NULL CHECK (peran IN ('guru','puskesmas')),
  paud_id       BIGINT REFERENCES kpsp.paud(id),
  aktif         INTEGER NOT NULL DEFAULT 0,    -- guru baru = 0 sampai diaktifkan Puskesmas
  dibuat        TEXT NOT NULL DEFAULT (now()::text));
CREATE INDEX ix_pengguna_paud ON kpsp.pengguna(paud_id);

-- Anak yang diskrining
CREATE TABLE kpsp.anak (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paud_id     BIGINT NOT NULL REFERENCES kpsp.paud(id),
  nama        TEXT NOT NULL,
  jk          TEXT NOT NULL CHECK (jk IN ('L','P')),
  tgl_lahir   TEXT NOT NULL,                   -- ISO 'YYYY-MM-DD'
  nama_ortu   TEXT,
  dibuat_oleh BIGINT REFERENCES kpsp.pengguna(id),
  dibuat      TEXT NOT NULL DEFAULT (now()::text));
CREATE INDEX ix_anak_paud ON kpsp.anak(paud_id);
CREATE INDEX ix_anak_dibuat_oleh ON kpsp.anak(dibuat_oleh);

-- Hasil skrining (KPSP + antropometri + tindak lanjut Puskesmas)
CREATE TABLE kpsp.skrining (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anak_id     BIGINT NOT NULL REFERENCES kpsp.anak(id) ON DELETE CASCADE,
  tgl_periksa TEXT NOT NULL,                   -- ISO 'YYYY-MM-DD'
  umur_teks TEXT, umur_bulan INTEGER, kpsp_umur INTEGER,
  jawaban TEXT,                                -- 10 karakter Y/T, mis. 'YYYYYYYYTT'
  skor INTEGER, hasil_kpsp TEXT,               -- 'Sesuai umur' | 'Meragukan' | 'Penyimpangan'
  bb DOUBLE PRECISION, tb DOUBLE PRECISION, cara_ukur TEXT,
  lk DOUBLE PRECISION, lila DOUBLE PRECISION, imt DOUBLE PRECISION,
  z_bbu DOUBLE PRECISION, z_tbu DOUBLE PRECISION, z_bbtb DOUBLE PRECISION,
  z_imtu DOUBLE PRECISION, z_lku DOUBLE PRECISION,
  st_bbu TEXT, st_tbu TEXT, st_bbtb TEXT, st_imtu TEXT, st_lku TEXT, st_lila TEXT,
  status_gizi TEXT, masalah_gizi INTEGER, catatan_guru TEXT,
  tindak_lanjut TEXT, catatan_puskesmas TEXT,
  diverifikasi_oleh BIGINT REFERENCES kpsp.pengguna(id), diverifikasi_pada TEXT,
  dibuat_oleh BIGINT REFERENCES kpsp.pengguna(id),
  dibuat TEXT NOT NULL DEFAULT (now()::text));
CREATE INDEX ix_skr_anak ON kpsp.skrining(anak_id, tgl_periksa DESC, id DESC);
CREATE INDEX ix_skr_verif ON kpsp.skrining(diverifikasi_oleh);
CREATE INDEX ix_skr_dibuat_oleh ON kpsp.skrining(dibuat_oleh);

-- schema kpsp tidak diekspos ke API publik; tutup akses role anon/authenticated
REVOKE ALL ON SCHEMA kpsp FROM PUBLIC, anon, authenticated;
